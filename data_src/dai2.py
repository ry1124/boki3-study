def moving_average(lines):
    """商品有高帳(移動平均法)を計算する。lines: ("in"|"out", 日付, 数量, 単価)。払出しの単価は無視して平均単価を使う"""
    qty = amt = 0
    out, avg_after = {}, {}
    for kind, day, q, price in lines:
        if kind == "in":
            qty, amt = qty + q, amt + q * price
            avg_after[day] = amt / qty
        else:
            unit = amt / qty
            assert unit == int(unit), f"{day}: 平均単価が割り切れない"
            out[day] = int(unit) * q
            qty, amt = qty - q, amt - int(unit) * q
    return out, avg_after, qty, amt


